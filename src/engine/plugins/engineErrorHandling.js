"use strict";

const fs = require("node:fs");
const path = require("node:path");

const GENERATED_MARKER = "// @generated by nextjs-engine global error handling — do not edit.";
const WARNING_STATE_KEY = Symbol.for("nextjs-engine.global-error-handling-warnings");

function normalizeImportPath(value) {
	const withoutExtension = value.replace(/\.(?:js|jsx|ts|tsx|mjs|cjs)$/, "");
	const normalized = withoutExtension.split(path.sep).join("/");
	return normalized.startsWith(".") ? normalized : "./" + normalized;
}

function reporterSpecifier(rootDirectory, fromDirectory) {
	const candidates = [
		path.join(rootDirectory, "src", "engine", "errors", "engineErrorReporter.js"),
		// When this plugin runs from node_modules, resolve the sibling reporter from
		// the installed package instead of assuming its package root is exported.
		path.resolve(__dirname, "../errors/engineErrorReporter.js"),
	];
	for (const sourceFile of candidates) {
		try {
			if (fs.statSync(sourceFile).isFile()) return normalizeImportPath(path.relative(fromDirectory, sourceFile));
		} catch {
			// Try the next known package layout.
		}
	}
	return "nextjs-engine";
}

function warnOnce(rootDirectory, code, message, enabled) {
	if (!enabled) return;
	const state = globalThis[WARNING_STATE_KEY] || (globalThis[WARNING_STATE_KEY] = { reported: new Set() });
	const key = path.resolve(rootDirectory) + "|" + code + "|" + message;
	if (state.reported.has(key)) return;
	state.reported.add(key);
	console.warn("[nextjs-engine][errors][" + code + "] WARNING " + message
		+ "\n  See docs/3/global-error-handling.md for the safe integration path.");
}

function writeGeneratedFile(rootDirectory, filename, contents, options = {}) {
	let existing;
	try {
		existing = fs.readFileSync(filename, "utf8");
	} catch {
		existing = null;
	}
	if (existing !== null && !existing.startsWith(GENERATED_MARKER)) {
		const relative = path.relative(rootDirectory, filename).split(path.sep).join("/");
		warnOnce(rootDirectory, options.warningCode || "WNE001",
			"Preserving user-owned " + relative + "; the Engine will not overwrite custom error handling. Integrate reportEngineError() manually if you want its structured diagnostics.",
			options.development);
		return { path: relative, status: "preserved" };
	}
	try {
		fs.mkdirSync(path.dirname(filename), { recursive: true });
		if (existing !== contents) fs.writeFileSync(filename, contents, "utf8");
		return {
			path: path.relative(rootDirectory, filename).split(path.sep).join("/"),
			status: existing === contents ? "unchanged" : "generated",
		};
	} catch (error) {
		const relative = path.relative(rootDirectory, filename).split(path.sep).join("/");
		warnOnce(rootDirectory, "WNE002",
			"Could not generate " + relative + ": " + (error && error.message ? error.message : String(error)),
			true);
		return { path: relative, status: "failed" };
	}
}

function errorRouteSource(importPath) {
	return [
		GENERATED_MARKER,
		'"use client";',
		'import { useEffect } from "react";',
		'import { reportEngineError } from ' + JSON.stringify(importPath) + ';',
		"",
		"type EngineRouteErrorProps = {",
		"\terror: Error & { digest?: string };",
		"\treset: () => void;",
		"};",
		"",
		"export default function EngineRouteError({ error, reset }: EngineRouteErrorProps) {",
		"\tuseEffect(() => {",
		"\t\treportEngineError(error, {",
		'\t\t\tcode: "NE-ROUTE-001",',
		'\t\t\tsource: "next-route-error",',
		"\t\t\troute: window.location.pathname,",
		"\t\t\tdigest: error.digest,",
		'\t\t\tincludeStack: process.env.NODE_ENV === "development",',
		"\t\t});",
		"\t}, [error]);",
		"",
		"\treturn (",
		'\t\t<main role="alert" style={{ minHeight: "100vh", display: "grid", placeContent: "center", padding: "2rem", fontFamily: "system-ui, sans-serif" }}>',
		"\t\t\t<h1>Something went wrong.</h1>",
		"\t\t\t<p>The page encountered an unexpected error. Your other routes may still work.</p>",
		'\t\t\t{process.env.NODE_ENV === "development" ? <pre style={{ maxWidth: "min(80vw, 900px)", whiteSpace: "pre-wrap", overflowWrap: "anywhere" }}>{error.message}</pre> : <p>Error reference: {error.digest || "unavailable"}</p>}',
		'\t\t\t<button type="button" onClick={reset} style={{ justifySelf: "start", padding: "0.6rem 1rem", cursor: "pointer" }}>Try again</button>',
		"\t\t</main>",
		"\t);",
		"}",
		"",
	].join("\n");
}

function globalErrorRouteSource(importPath) {
	return [
		GENERATED_MARKER,
		'"use client";',
		'import { useEffect } from "react";',
		'import { reportEngineError } from ' + JSON.stringify(importPath) + ';',
		"",
		"type EngineGlobalErrorProps = {",
		"\terror: Error & { digest?: string };",
		"\tunstable_retry: () => void;",
		"};",
		"",
		"export default function EngineGlobalError({ error, unstable_retry }: EngineGlobalErrorProps) {",
		"\tuseEffect(() => {",
		"\t\treportEngineError(error, {",
		'\t\t\tcode: "NE-GLOBAL-001",',
		'\t\t\tsource: "next-global-error",',
		"\t\t\troute: window.location.pathname,",
		"\t\t\tdigest: error.digest,",
		'\t\t\tincludeStack: process.env.NODE_ENV === "development",',
		"\t\t});",
		"\t}, [error]);",
		"",
		"\treturn (",
		'\t\t<html lang="en">',
		'\t\t\t<body style={{ minHeight: "100vh", margin: 0, display: "grid", placeContent: "center", padding: "2rem", fontFamily: "system-ui, sans-serif" }}>',
		'\t\t\t\t<main role="alert">',
		"\t\t\t\t\t<h1>The application encountered an error.</h1>",
		"\t\t\t\t\t<p>Try again to reload the affected application tree.</p>",
		'\t\t\t\t\t{process.env.NODE_ENV === "development" ? <pre style={{ maxWidth: "min(80vw, 900px)", whiteSpace: "pre-wrap", overflowWrap: "anywhere" }}>{error.message}</pre> : <p>Error reference: {error.digest || "unavailable"}</p>}',
		'\t\t\t\t\t<button type="button" onClick={unstable_retry} style={{ padding: "0.6rem 1rem", cursor: "pointer" }}>Try again</button>',
		"\t\t\t\t</main>",
		"\t\t\t</body>",
		"\t\t</html>",
		"\t);",
		"}",
		"",
	].join("\n");
}

function instrumentationSource(importPath) {
	return [
		GENERATED_MARKER,
		'import type { Instrumentation } from "next";',
		'import { installEngineUncaughtExceptionMonitor, reportEngineError } from ' + JSON.stringify(importPath) + ';',
		"",
		"export function register(): void {",
		"\tinstallEngineUncaughtExceptionMonitor();",
		"}",
		"",
		"export const onRequestError: Instrumentation.onRequestError = async (error, request, context) => {",
		"\tconst errorValue = error as (Error & { digest?: unknown }) | null | undefined;",
		"\tconst diagnosticError = error instanceof Error ? error : new Error(String(error));",
		'\tconst digest = typeof errorValue?.digest === "string" ? errorValue.digest : undefined;',
		"\treportEngineError(diagnosticError, {",
		'\t\tcode: "NE-REQUEST-001",',
		'\t\tsource: "next-request",',
		"\t\troute: context && context.routePath,",
		"\t\trequestPath: request && request.path,",
		"\t\trequestMethod: request && request.method,",
		"\t\tdigest,",
		'\t\tdetail: "Next.js " + (context && context.routerKind ? context.routerKind : "router") + " " + (context && context.routeType ? context.routeType : "request") + " failure.",',
		"\t\tincludeStack: true,",
		"\t});",
		"};",
		"",
	].join("\n");
}

function appDirectory(rootDirectory) {
	const rootApp = path.join(rootDirectory, "app");
	const srcApp = path.join(rootDirectory, "src", "app");
	if (fs.existsSync(rootApp) && fs.statSync(rootApp).isDirectory()) return rootApp;
	if (fs.existsSync(srcApp) && fs.statSync(srcApp).isDirectory()) return srcApp;
	return null;
}

function prepareEngineErrorHandling(options = {}) {
	const rootDirectory = path.resolve(options.rootDir || process.cwd());
	const development = options.development === undefined
		? process.env.NODE_ENV === "development" || process.argv.slice(2).some((arg) => arg === "dev")
		: options.development === true;
	const appDir = appDirectory(rootDirectory);
	const generated = [];
	const preserved = [];

	if (appDir) {
		const routeImport = reporterSpecifier(rootDirectory, appDir);
		const routeFiles = [
			{ name: "error.tsx", contents: errorRouteSource(routeImport), warningCode: "WNE003" },
			{ name: "global-error.tsx", contents: globalErrorRouteSource(routeImport), warningCode: "WNE004" },
		];
		for (const route of routeFiles) {
			const result = writeGeneratedFile(rootDirectory, path.join(appDir, route.name), route.contents, {
				development,
				warningCode: route.warningCode,
			});
			if (result.status === "preserved") preserved.push(result.path);
			else if (result.status === "generated" || result.status === "unchanged") generated.push(result.path);
		}
	}

	const candidates = [
		path.join(rootDirectory, "instrumentation.ts"),
		path.join(rootDirectory, "instrumentation.js"),
		path.join(rootDirectory, "src", "instrumentation.ts"),
		path.join(rootDirectory, "src", "instrumentation.js"),
	];
	let instrumentationFile = candidates.find((candidate) => fs.existsSync(candidate));
	if (!instrumentationFile) {
		const sourceRoot = appDir && path.dirname(appDir) === path.join(rootDirectory, "src")
			? path.join(rootDirectory, "src")
			: rootDirectory;
		instrumentationFile = path.join(sourceRoot, "instrumentation.ts");
	}
	const instrumentationImport = reporterSpecifier(rootDirectory, path.dirname(instrumentationFile));
	const instrumentationResult = writeGeneratedFile(
		rootDirectory,
		instrumentationFile,
		instrumentationSource(instrumentationImport),
		{ development, warningCode: "WNE005" },
	);
	if (instrumentationResult.status === "preserved") preserved.push(instrumentationResult.path);
	else if (instrumentationResult.status === "generated" || instrumentationResult.status === "unchanged") generated.push(instrumentationResult.path);

	return { appDirectory: appDir, generated, preserved, instrumentation: instrumentationResult };
}

module.exports = {
	GENERATED_MARKER,
	prepareEngineErrorHandling,
	errorRouteSource,
	globalErrorRouteSource,
	instrumentationSource,
	reporterSpecifier,
};
